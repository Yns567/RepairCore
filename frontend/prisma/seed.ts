async function main() {
  for (const category of categories) {
    await prisma.category.upsert({
      where: { slug: category.slug },
      update: { name: category.name },
      create: category,
    });
  }

  for (const product of products) {
    await prisma.product.upsert({
      where: { slug: product.slug },
      // Seed products are starter records. Once an administrator edits a
      // product (especially its Blob-backed images), rerunning the seed must
      // not overwrite those live values or desynchronise image/imageBlobPath.
      update: {},
      create: product,
    });
  }

  for (const plan of plans) {
    await prisma.subscriptionPlan.upsert({
      where: { slug: plan.slug },
      update: { ...plan, status: "ACTIVE" },
      create: { ...plan, status: "ACTIVE" },
    });
  }

  for (const service of gsmServices) {
    await prisma.gsmService.upsert({
      where: { slug: service.slug },
      update: { ...service, status: "ACTIVE" },
      create: { ...service, status: "ACTIVE" },
    });
  }

  console.log(`Seed complete: ${products.length} products, ${plans.length} software plans and ${gsmServices.length} GSM services are ready.`);
}

main()
  .catch((error) => {
    console.error(error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
